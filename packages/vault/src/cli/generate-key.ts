/**
 * Generates a master key and writes it into the root .env as WORKBOX_MASTER_KEY, without ever
 * printing it. Refuses to overwrite an existing key: replacing it would make every stored
 * credential undecryptable (use key rotation instead, see docs/adr/003).
 */
import { chmodSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { PROJECT_ROOT } from '#core';
import { generateMasterKey } from '../keyring.js';

const envPath = join(PROJECT_ROOT, '.env');

function main(): number {
  if (!existsSync(envPath)) {
    process.stderr.write('No .env found. Run: cp .env.example .env\n');
    return 1;
  }
  const content = readFileSync(envPath, 'utf8');
  const line = /^WORKBOX_MASTER_KEY=(.*)$/m.exec(content);
  if (line && line[1]!.trim() !== '') {
    process.stderr.write(
      'WORKBOX_MASTER_KEY is already set in .env; not overwriting it.\n' +
        'To rotate keys, see docs/adr/003-credential-vault-and-master-key.md.\n',
    );
    return 1;
  }
  const entry = `WORKBOX_MASTER_KEY=${generateMasterKey()}`;
  const updated = line
    ? content.replace(/^WORKBOX_MASTER_KEY=.*$/m, entry)
    : `${content.replace(/\n?$/, '\n')}\n# Vault master key (generated by pnpm vault:generate-key). Back it up; never commit it.\n${entry}\n`;
  writeFileSync(envPath, updated);
  // Owner-only: .env now holds the key that decrypts every stored token.
  chmodSync(envPath, 0o600);
  process.stdout.write(
    'Generated a new master key and saved it to .env as WORKBOX_MASTER_KEY.\n' +
      'Back it up somewhere safe (separately from database backups): without it, stored\n' +
      'credentials cannot be decrypted and must be re-entered.\n',
  );
  return 0;
}

process.exitCode = main();
